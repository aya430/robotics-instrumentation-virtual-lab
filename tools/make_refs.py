#!/usr/bin/env python3
"""Regenerate js/data/z-refs.js and reference/notes-index.js from the course PDFs.
Usage (from the project root, needs poppler's pdftotext):
    python3 tools/make_refs.py "<Unit Wise Detailed Notes.pdf>" "<Unit 1 slides.pdf>" "<Unit 2>" "<Unit 3>" "<Unit 4>"
Section start pages are read from the table of contents of the notes (printed page
numbers); the PDF page is printed page + offset. Slide numbers are the first slide of
each deck whose title starts with the section number. Nothing is guessed: a section
without a matching slide gets slide = null."""
import json, re, shutil, subprocess, sys, os
notes, decks = sys.argv[1], sys.argv[2:6]
text = lambda f: subprocess.run(['pdftotext', '-layout', f, '-'], capture_output=True, text=True).stdout.split('\f')
t = text(notes); toc = {}
for p in t[:22]:
    for m in re.finditer(r'^\s*(\d\.\d{1,2})\s+(.+?)\s*(?:\. ?)+\s*(\d+)\s*$', p, re.M):
        if re.match(r'[A-Z]', m.group(2)) and not re.search(r':\s*\(?a\)|gauge$', m.group(2)): toc.setdefault(m.group(1), (m.group(2).strip(), int(m.group(3))))
first = toc['1.1']; offset = next(i for i, p in enumerate(t[15:60], 16) if re.search(r'^\s*1\.1\s+' + re.escape(first[0]) + r'\s*$', p, re.M)) - first[1]
slides = {}
for n, f in enumerate(decks, 1):
    for i, p in enumerate(text(f)):
        l = [x.strip() for x in p.strip().split('\n') if x.strip()]
        m = l and re.match(r'^(%d\.\d{1,2})\s+\S' % n, l[0])
        if m and m.group(1) not in slides: slides[m.group(1)] = i + 1
keys = sorted(toc, key=lambda k: [int(x) for x in k.split('.')])
out = {'notesFile': 'reference/Unit-Wise-Detailed-Notes.pdf', 'notesOffset': offset, 'sections': {k: {'title': toc[k][0], 'page': toc[k][1], 'slide': slides.get(k)} for k in keys}}
open('js/data/z-refs.js', 'w', encoding='utf8').write("/* generated by tools/make_refs.py from the supplied PDFs: section start pages of 'Unit Wise Detailed Notes.pdf' (printed page numbers; PDF page = printed + notesOffset) and of the unit slide decks. */\n(function(){'use strict';const RIL=window.RIL=window.RIL||{};RIL.refs=" + json.dumps(out, ensure_ascii=False) + ";})();\n")
os.makedirs('reference', exist_ok=True); shutil.copyfile(notes, 'reference/Unit-Wise-Detailed-Notes.pdf')
open('reference/notes-index.js', 'w', encoding='utf8').write('/* text of each page of the course notes, for the library search (generated by tools/make_refs.py) */\nwindow.RIL_NOTES_PAGES=' + json.dumps([re.sub(r'\s+', ' ', x).strip() for x in t if x.strip() or True][:len(t) - 1], ensure_ascii=False) + ';\n')
print(len(keys), 'sections; offset', offset, '; sections without a slide:', [k for k in keys if k not in slides])
