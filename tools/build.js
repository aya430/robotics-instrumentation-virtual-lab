#!/usr/bin/env node
/* Build script: bundles data + simulations, generates every HTML page shell,
   quiz JSON files and the generated documentation tables.
   Usage:  node tools/build.js           (run from the project root)        */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const rd = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const wr = (p, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true }); fs.writeFileSync(path.join(ROOT, p), s); };

/* 1. bundles */
const list = dir => fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith('.js')).sort().map(f => dir + '/' + f);
const banner = f => `\n/* ===== ${f} ===== */\n`;
const dataFiles = list('js/data'), simFiles = list('js/sims');
wr('js/bundle-data.js', '/* generated by tools/build.js — edit files in js/data/ */' + dataFiles.map(f => banner(f) + rd(f)).join('\n'));
wr('js/bundle-sims.js', '/* generated by tools/build.js — edit files in js/sims/ */' + simFiles.map(f => banner(f) + rd(f)).join('\n'));

/* 2. load metadata in a stub environment */
const M = require(path.join(ROOT, 'js/equation-engine.js'));
const sims = {}, order = [];
const window = { RIL: { M, sims, simOrder: order, defineSim: d => { sims[d.id] = d; order.push(d.id); }, draw: {}, ui: {}, h: () => ({}), three: { ROBOTS: {} } }, RIL_CONFIG: {} };
const self = window; // eslint-disable-line no-unused-vars
new Function('window', 'self', 'RIL', rd('js/bundle-data.js') + '\n' + rd('js/bundle-sims.js'))(window, window, window.RIL);
const RIL = window.RIL; const units = RIL.units;
const pad = n => String(n).padStart(2, '0');

/* 3. page shells */
const FONTS = '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@100..125,400..800&family=Source+Serif+4:ital,opsz,wght@0,8..60,400..700;1,8..60,400&display=swap" rel="stylesheet">';
function shell({ root, title, desc, page, attrs = '', heading = '', math = true, quiz = false }) {
  const s = f => `<script src="${root}${f}"></script>`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${desc.replace(/"/g, '&quot;')}">
<link rel="icon" href="${root}assets/icons/favicon.svg" type="image/svg+xml">
${FONTS}
<link rel="stylesheet" href="${root}css/global.css">
<link rel="stylesheet" href="${root}css/dashboard.css">
<link rel="stylesheet" href="${root}css/simulation.css">
<link rel="stylesheet" href="${root}css/responsive.css">
${math ? `<script>window.MathJax={tex:{inlineMath:[['\\\\(','\\\\)']],displayMath:[['\\\\[','\\\\]']]},svg:{fontCache:'global'},options:{enableMenu:false}};</script>
<script async id="MathJax-script" src="${root}assets/vendor/tex-svg.js"></script>` : ''}
</head>
<body data-root="${root}" data-page="${page}" ${attrs}>
<a class="skip" href="#main">Skip to content</a>
<div id="app-head"></div>
<main id="main" class="wrap"><noscript><h1>${heading || title}</h1><p>This laboratory needs JavaScript to run its simulations. Please enable JavaScript.</p></noscript></main>
<div id="app-foot"></div>
${s('js/config.js')}
${s('assets/vendor/three.min.js')}
${s('assets/vendor/OrbitControls.js')}
${s('assets/vendor/chart.umd.js')}
${s('assets/vendor/gsap.min.js')}
${s('js/equation-engine.js')}
${s('js/simulation-engine.js')}
${s('js/three-kit.js')}
${s('js/bundle-data.js')}
${s('js/bundle-sims.js')}
${quiz ? s('js/quiz-engine.js') : ''}
${s('js/navigation.js')}
${s('js/app.js')}
</body>
</html>
`;
}
const SITE = 'Robotics & Instrumentation Virtual Lab';
const pages = [];
const add = (file, o) => { wr(file, shell(o)); pages.push(file); };
add('index.html', { root: '', title: 'Robotics & Instrumentation | Interactive Virtual Learning Laboratory', desc: 'Interactive robotics and instrumentation virtual laboratory: four units, topic modules, 2D/3D simulations, virtual experiments and quizzes.', page: 'home', math: false });
add('syllabus.html', { root: '', title: 'Course Syllabus | ' + SITE, desc: 'Four-unit syllabus of Robotics and Instrumentation with topic, simulation and experiment mapping.', page: 'syllabus', math: false });
add('simulations.html', { root: '', title: 'All Simulations | ' + SITE, desc: 'Catalogue of interactive robotics and instrumentation simulations.', page: 'sims', math: false });
add('experiments.html', { root: '', title: 'Virtual Experiments | ' + SITE, desc: 'Virtual experiments mapped to the syllabus.', page: 'exps', math: false });
add('practice.html', { root: '', title: 'Practice Questions | ' + SITE, desc: 'Unit-wise practice quizzes with immediate feedback.', page: 'practice', quiz: true });
add('about.html', { root: '', title: 'About | ' + SITE, desc: 'About the Robotics & Instrumentation virtual laboratory.', page: 'about', math: false });
units.forEach(u => {
  add(`units/unit-${u.n}/index.html`, { root: '../../', title: `Unit ${u.roman}: ${u.title} | ${SITE}`, desc: u.syllabus, page: 'unit', attrs: `data-unit="${u.n}"`, heading: `Unit ${u.roman}: ${u.title}`, math: false });
  u.topics.forEach(t => add(`units/unit-${u.n}/topic-${pad(t.n)}.html`, { root: '../../', title: `${t.title} | Unit ${u.roman} | ${SITE}`, desc: (t.blurb || t.title).replace(/<[^>]+>/g, ''), page: 'topic', attrs: `data-unit="${u.n}" data-topic="${t.id}"`, heading: t.title }));
});
order.forEach(id => { const s = sims[id]; add(`simulations/${s.category}/${id}.html`, { root: '../../', title: `${s.title} | Simulation | ${SITE}`, desc: (s.description || s.title).replace(/<[^>]+>/g, ''), page: 'sim', attrs: `data-sim="${id}"`, heading: s.title }); });
(RIL.experiments || []).forEach(e => add(`experiments/unit-${e.unit}/${e.id}.html`, { root: '../../', title: `${e.title} | Virtual Experiment | ${SITE}`, desc: e.aim.replace(/<[^>]+>/g, ''), page: 'exp', attrs: `data-exp="${e.id}"`, heading: e.title }));
// 404: GitHub Pages serves this from any depth, so use absolute-free links resolved by script
wr('404.html', `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Page not found | ${SITE}</title>
<style>body{font-family:Archivo,system-ui,sans-serif;background:#0e1d38;color:#dbe5f5;display:grid;place-items:center;min-height:100vh;margin:0;padding:16px}a{color:#f2a516}main{max-width:560px}</style></head>
<body><main><h1>Page not found</h1><p>The address does not match any page of the laboratory. It may have been mistyped or the page was moved.</p><p><a id="home" href="index.html">Go to the laboratory home page</a></p></main>
<script>/* find the project root: first path segment on github.io project sites */var p=location.pathname.split('/').filter(Boolean);var root=(location.hostname.endsWith('github.io')&&p.length)?'/'+p[0]+'/':'/';document.getElementById('home').href=root+'index.html';</script></body></html>`);

/* 4. quiz JSON (same source as js/data/quiz-*.js) */
Object.entries(RIL.quiz || {}).forEach(([u, qs]) => wr(`quizzes/unit-${u}.json`, JSON.stringify({ unit: +u, title: units[u - 1].title, questions: qs }, null, 2)));

/* 5. generated documentation */
const simLink = id => sims[id] ? `[${sims[id].title}](../simulations/${sims[id].category}/${id}.html)` : `MISSING:${id}`;
let map = `# Syllabus Content Mapping\n\nGenerated by \`tools/build.js\` from the data files, so it always matches the website.\nEvery syllabus topic of the four units maps to a theory module, its animation/simulation, its mathematical model, a virtual experiment (where one is defined) and assessment questions.\n\n`;
map += `| Unit | Topics | Simulations | Experiments | Quiz questions |\n|---|---|---|---|---|\n` + units.map(u => `| ${u.roman} | ${u.topics.length} | ${new Set(u.topics.flatMap(t => t.sims || [])).size} | ${(RIL.experiments || []).filter(e => e.unit === u.n).length} | ${(RIL.quiz[u.n] || []).length} |`).join('\n') + '\n\n';
units.forEach(u => {
  map += `## Unit ${u.roman} – ${u.title}\n\n**Syllabus text:** ${u.syllabus}\n\n| # | Syllabus topic | Theory module | Animation / interactive simulation | Mathematical model | Virtual experiment | Assessment |\n|---|---|---|---|---|---|---|\n`;
  u.topics.forEach(t => {
    const exps = (RIL.experiments || []).filter(e => (e.topics || []).includes(t.id)).map(e => `[${e.title}](../experiments/unit-${u.n}/${e.id}.html)`).join('<br>') || '— (covered by topic simulation)';
    const models = (t.model || []).map(m => (m.title || '').replace(/<[^>]+>/g, '')).filter(Boolean).join('; ') || 'Qualitative (no equation required)';
    const qn = (RIL.quiz[u.n] || []).filter(q => (q.topic || '') === t.id).length;
    map += `| ${t.n} | ${t.title} | [topic-${pad(t.n)}.html](../units/unit-${u.n}/topic-${pad(t.n)}.html) — notes ${(t.refs || '').replace(/\|/g, '/')} | ${(t.sims || []).map(simLink).join('<br>')} | ${models} | ${exps} | ${(t.questions || []).length} topic questions; ${qn} quiz items |\n`;
  });
  map += '\n';
});
wr('docs/SYLLABUS_CONTENT_MAPPING.md', map);
let cat = `# Simulation Catalog\n\nGenerated by \`tools/build.js\`. ${order.length} simulations.\n\n| # | Simulation | Unit | Type | Category folder | Controls | Live readouts | Graphs | Topics |\n|---|---|---|---|---|---|---|---|---|\n`;
order.forEach((id, i) => { const s = sims[id]; const tps = units.flatMap(u => u.topics.filter(t => (t.sims || []).includes(id)).map(t => `U${u.roman}-T${t.n}`)); cat += `| ${i + 1} | **${s.title}** (\`${id}\`)<br>${(s.description || '').replace(/\|/g, '/')} | ${s.unit} | ${s.kind.toUpperCase()} | ${s.category} | ${(s.controls || []).filter(c => c.label).map(c => c.label.replace(/<[^>]+>/g, '')).join(', ')} | ${(s.readouts || []).map(r => r.label.replace(/<[^>]+>/g, '')).join(', ')} | ${(s.charts || []).map(c => c.title).join(', ') || '—'} | ${tps.join(', ')} |\n`; });
wr('docs/SIMULATION_CATALOG.md', cat);

/* 6. sanity checks */
const problems = [];
units.forEach(u => u.topics.forEach(t => { if (!t.sims || !t.sims.length) problems.push(`topic ${t.id} has no simulation`); (t.sims || []).forEach(id => { if (!sims[id]) problems.push(`topic ${t.id} references missing sim ${id}`); }); }));
(RIL.experiments || []).forEach(e => { if (!sims[e.sim]) problems.push(`experiment ${e.id} references missing sim ${e.sim}`); });
const orphan = order.filter(id => !units.some(u => u.topics.some(t => (t.sims || []).includes(id))));
orphan.forEach(id => problems.push(`sim ${id} is not used by any topic`));
fs.writeFileSync(path.join(ROOT, 'tests/pages.json'), JSON.stringify(pages, null, 1));
console.log(`pages: ${pages.length}, sims: ${order.length}, topics: ${units.reduce((a, u) => a + u.topics.length, 0)}, experiments: ${(RIL.experiments || []).length}, quiz items: ${Object.values(RIL.quiz || {}).reduce((a, q) => a + q.length, 0)}`);
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exitCode = 1; }
